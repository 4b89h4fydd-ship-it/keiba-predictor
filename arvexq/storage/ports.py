"""Explicit storage interfaces; source dictionaries retain their existing schema."""
from typing import Protocol


class RaceSnapshotPorts(Protocol):
    def _compact_display_snapshot(self, detail: dict) -> dict: ...
    def _strip_excluded(self, payload: dict) -> dict: ...
    def _prediction_clock_state(self, detail: dict) -> tuple[str, int | None]: ...


class PreparedSnapshotPorts(RaceSnapshotPorts, Protocol):
    def _prediction_audit_from_lock(self, detail: dict) -> dict | None: ...
    def _today_iso(self) -> str: ...
