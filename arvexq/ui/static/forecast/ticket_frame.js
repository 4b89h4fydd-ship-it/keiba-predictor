'use strict';
function esc(x){
 return String(x==null?'':x).replace(/&/g,'&amp;').replace(/</g,'&lt;')
   .replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&#39;');
}
function revisionStatus(r){
 var live=root.ARVEXQProductionPrediction&&root.ARVEXQProductionPrediction.current();
 var rev=r&&r._forecastRevisionView,plan=rev&&rev.betPlan;
 if(!live||!/^learned-revision-/.test(live.source||'')||!rev||rev.raceId!==r.id||rev.raceDate!==r.date||!plan)return '';
 var note=live.source==='learned-revision-retrospective'?'事後再分析の買い目比較':'発走前の仮予想の買い目比較';
 var rows=Array.isArray(plan.comparisons)?plan.comparisons:[];
 return '<div class="revision-bet-status"><p>'+esc(note)+'：'+esc(plan.decision||'見送り')+'</p><p class="muted">'+esc(plan.reason||'')+'</p>'+rows.map(function(row){
   return '<p><b>'+esc(row.kind)+'</b>：'+esc(row.decision||'見送り')+' — '+esc(row.reason||'')+'</p>';
 }).join('')+'</div>';
}
/* Re-rank only already sealed picks by the saved Stage64 pre-off distribution.
   This never creates new combinations or consults finish results. */
function sealedFive(r,server){
 var total=server.reduce(function(n,item){return n+(Array.isArray(item.combos)?item.combos.length:0);},0);
 if(total<=5)return server;
 var probs=r&&r.prediction&&r.prediction.stages&&r.prediction.stages.probability&&r.prediction.stages.probability.value;
 var raw=probs&&probs.trifecta;
 if(!raw)return server;
 var joint=Array.isArray(raw)?raw.map(function(x){return {finish:x.combo,prob:Number(x.probability)};}):
   Object.keys(raw).map(function(key){return {finish:key.split(',').map(Number),prob:Number(raw[key])};});
 var ranked=[];
 server.forEach(function(item){
  (item.combos||[]).forEach(function(combo){
   var nums=combo.map(Number);
   var probability=joint.reduce(function(sum,row){
    var finish=row.finish||[];
    var matches=item.kind==='馬単'?finish[0]===nums[0]&&finish[1]===nums[1]:
      item.kind==='馬連'?finish.slice(0,2).every(function(n){return nums.indexOf(n)>=0;}):
      item.kind==='ワイド'?nums.every(function(n){return finish.slice(0,3).indexOf(n)>=0;}):
      item.kind==='3連複'?finish.slice(0,3).every(function(n){return nums.indexOf(n)>=0;}):
      item.kind==='3連単'?finish.slice(0,3).every(function(n,i){return n===nums[i];}):false;
    return sum+(matches&&Number.isFinite(row.prob)?row.prob:0);
   },0);
   ranked.push({item:item,combo:combo,probability:probability});
  });
 });
 ranked.sort(function(a,b){return b.probability-a.probability||
  String(a.item.kind).localeCompare(String(b.item.kind))||
  String(a.combo).localeCompare(String(b.combo));});
 var selected=[];
 ranked.slice(0,5).forEach(function(row){
  var group=selected.filter(function(x){return x.kind===row.item.kind;})[0];
  if(!group){group={kind:row.item.kind,combos:[],points:0,reason:'保存済み発走前確率・全券種合計上位5点'};selected.push(group);}
  group.combos.push(row.combo);group.points++;
 });
 return selected;
}
/* Compact notation for bet groups whose saved combinations form a
   complete mechanical pattern (user format, 2026-10-31): legs are
   joined by '-', horses inside a leg by '.', horse numbers only, in
   prediction-mark order. A group is summarized ONLY when its combos
   are exactly the complete set generated by the pattern; anything
   else keeps the enumerated chips, so a partial group is never
   presented as a formation/box/axis bet it is not.
   - ordered kinds (3連単/馬単): per-position leg sets whose complete
     distinct permutations equal the combos -> "8.5.2-8.5.2.4.6-...".
   - unordered kinds (馬連/3連複/ワイド): a full box -> "8.5.2.4.6"
     (rendered with a BOX badge so it is not mistaken for a single
     combination); a shared axis plus every partner combination ->
     "8-5.2.4". summarizeGroup returns {type, text} with type one of
     'formation' | 'box' | 'axis' so the renderer can label boxes. */
var ORDERED_KINDS={'3連単':1,'馬単':1};
var UNORDERED_KINDS={'馬連':1,'3連複':1,'ワイド':1};
function markOrderOf(r){
 var order={},marks=r&&Array.isArray(r.predictionMarks)?r.predictionMarks:[];
 marks.forEach(function(m,i){if(m&&m.horseNumber!=null)order[Number(m.horseNumber)]=i;});
 return order;
}
function sortByMark(nums,order){
 return nums.slice().sort(function(a,b){
  var oa=order.hasOwnProperty(a)?order[a]:Number.MAX_SAFE_INTEGER;
  var ob=order.hasOwnProperty(b)?order[b]:Number.MAX_SAFE_INTEGER;
  return oa-ob||a-b;
 });
}
function uniqNums(list){
 var seen={},out=[];
 list.forEach(function(n){if(!seen[n]){seen[n]=1;out.push(n);}});
 return out;
}
function chooseCombos(arr,k){
 var out=[];
 (function rec(start,cur){
  if(cur.length===k){out.push(cur.slice());return;}
  for(var i=start;i<arr.length;i++){cur.push(arr[i]);rec(i+1,cur);cur.pop();}
 })(0,[]);
 return out;
}
function summarizeGroup(item,r){
 var combos=(item&&item.combos)||[];
 if(!combos.length)return null;
 var norm=combos.map(function(c){return (c||[]).map(Number);});
 var bad=norm.some(function(c){return !c.length||c.some(function(n){return !Number.isFinite(n);})||
   uniqNums(c).length!==c.length;});
 if(bad)return null;
 var order=markOrderOf(r),kind=item&&item.kind,len=norm[0].length;
 if(norm.some(function(c){return c.length!==len;}))return null;
 if(ORDERED_KINDS[kind]){
  if(len<2)return null;
  var legs=[];
  for(var i=0;i<len;i++)legs.push(uniqNums(norm.map(function(c){return c[i];})));
  var want={},count=0;
  (function gen(pos,cur,used){
   if(pos===len){want[cur.join(',')]=1;count++;return;}
   legs[pos].forEach(function(n){
    if(!used[n]){used[n]=1;cur.push(n);gen(pos+1,cur,used);cur.pop();used[n]=0;}
   });
  })(0,[],{});
  var have={};
  norm.forEach(function(c){have[c.join(',')]=1;});
  if(Object.keys(have).length!==count)return null;
  for(var key in have)if(!want[key])return null;
  return {type:'formation',text:legs.map(function(leg){return sortByMark(leg,order).join('.');}).join('-')};
 }
 if(UNORDERED_KINDS[kind]){
  if(len<2)return null;
  var have2={};
  norm.forEach(function(c){
   have2[c.slice().sort(function(a,b){return a-b;}).join(',')]=1;
  });
  var haveCount=Object.keys(have2).length;
  var union=uniqNums(norm.reduce(function(a,c){return a.concat(c);},[]));
  if(union.length>=len){
   var box=chooseCombos(union,len);
   if(box.length===haveCount&&box.every(function(c){
    return have2[c.slice().sort(function(a,b){return a-b;}).join(',')];
   }))
    return {type:'box',text:sortByMark(union,order).join('.')};
  }
  var sorted=norm.map(function(c){return c.slice().sort(function(a,b){return a-b;});});
  var axis=sorted[0].filter(function(n){
   return sorted.every(function(c){return c.indexOf(n)>=0;});
  });
  if(axis.length>=1&&axis.length<len){
   var partners=union.filter(function(n){return axis.indexOf(n)<0;});
   var rest=chooseCombos(partners,len-axis.length);
   var axisOk=rest.length===haveCount&&rest.every(function(c){
    return have2[axis.concat(c).sort(function(a,b){return a-b;}).join(',')];
   });
   if(axisOk)return {type:'axis',text:sortByMark(axis,order).join('.')+'-'+sortByMark(partners,order).join('.')};
  }
  return null;
 }
 return null;
}
function combosHtml(item,r){
 var summary=summarizeGroup(item,r);
 if(summary){
  var badge=summary.type==='box'?'<span class="arv-three-box-label">BOX</span>':'';
  return badge+'<span class="arv-three-combo arv-three-summary">'+esc(summary.text)+'</span>';
 }
 return (item.combos||[]).map(function(c){
  return '<span class="arv-three-combo">'+esc((c||[]).join(' - '))+'</span>';
 }).join('');
}
/* Combined EV block (user decision 2026-11-04): when the payload
   carries place （複勝） EV ranges, the EV section lists ONLY the
   horses passing the combined gate — win EV >= 1.25 AND win
   probability >= 5% AND place EV lower bound >= 1.0 — taken from
   the payload's own combinedPicks, the same single source as the
   注 attention overlay in the entries table. Each row shows both
   EVs; the mark + 注 are stacked exactly like the mark cells. */
function combinedEvSection(placeEv,picks,winByNo,names,marksByNo,evLabel,evNote){
 var byNo={};
 (placeEv||[]).forEach(function(x){if(x&&x.horseNumber!=null)byNo[x.horseNumber]=x;});
 var rows=(picks||[]).map(function(no){
   var pe=byNo[no],w=winByNo[no];
   if(!pe||!w)return '';
   var mk=marksByNo[no]||{};
   var stack='<span style="display:inline-flex;flex-direction:column;align-items:center;line-height:1.05;vertical-align:middle;margin-right:5px">'+
     (mk.mark?'<span>'+esc(mk.mark)+'</span>':'')+
     '<span style="color:#e8a33d;font-weight:700">注</span></span>';
   return '<div class="arv-three-ticket"><div class="arv-three-ticket-head"><b>'+stack+
      esc(no)+'番'+(names[no]?' '+esc(names[no]):'')+'</b>'+
      '<span class="arv-three-count">単勝期待値 '+esc(Number(w.expectedValue).toFixed(2))+'</span></div>'+
      '<p class="arv-three-ticket-reason">勝率推定 '+esc((Number(w.winProbability)*100).toFixed(1))+
      '% × 単勝オッズ '+esc(Number(w.odds).toFixed(1))+
      ' ／ 3着内率 '+esc((Number(pe.top3Probability)*100).toFixed(1))+
      '% × 複勝オッズ '+esc(Number(pe.placeOddsLow).toFixed(1))+'〜'+esc(Number(pe.placeOddsHigh).toFixed(1))+
      ' → 3着内期待値 '+esc(Number(pe.expectedValueLow).toFixed(2))+'〜'+esc(Number(pe.expectedValueHigh).toFixed(2))+
      '（'+evLabel+'）</p></div>';
 }).join('');
 return '<section class="arv-three-section"><h3>期待値候補（'+evLabel+'）</h3>'+
   '<p class="arv-three-ticket-reason">表示条件：単勝期待値1.25以上・勝率5%以上 かつ 3着内期待値（下限）1.0以上の馬のみ表示（注印＝この条件を満たした馬）</p>'+
   (rows||'<p class="arv-three-ticket-reason">対象馬なし</p>')+
   '<p class="arv-three-ticket-reason">'+evNote+'</p></section>';
}
function marksByNoOf(r){
 var out={};
 (r&&Array.isArray(r.predictionMarks)?r.predictionMarks:[]).forEach(function(m){
   if(m&&m.horseNumber!=null)out[m.horseNumber]={mark:String(m.mark||''),attention:m.attention===true};
 });
 return out;
}
function contents(r,p){
 // Win-EV label follows the payload's own calibration status: races
 // published on the v9b lane (temperature calibration + market
 // blend) carry expectedValueStatus 'calibrated-estimate' and are
 // labelled as calibrated estimates; everything else keeps the
 // uncalibrated wording.
 var evCalibrated=!!(r&&r.unifiedForecast&&r.unifiedForecast.ticketPlan&&
   r.unifiedForecast.ticketPlan.expectedValueStatus==='calibrated-estimate');
 var evLabel=evCalibrated?'校正済みの推定値':'未校正の推定値';
 var evNote=evCalibrated?'確率は校正済み（温度校正＋市場ブレンド）の推定値です。期待値による購入推奨は行っていません。組み合わせ券種は発走前の実オッズ不足のため期待値を算出していません。':
   '確率は未校正で、勝率・回収率の実測検証は未完了です。組み合わせ券種は発走前の実オッズ不足のため期待値を算出していません。';
 var server=r&&r.predictionStatus==='ready'&&Array.isArray(r.recommendedBets)?sealedFive(r,r.recommendedBets):null;
 if(server){
   if(!server.length)return '<div class="ai-bet-box"><p class="muted">発走前の実オッズと着順確率から、期待回収率の条件を満たす買い目がありません。</p></div>';
   var rows=server.map(function(item){return '<div class="arv-three-ticket"><div class="arv-three-ticket-head"><b>'+esc(item.kind)+'</b><span class="arv-three-count">'+esc((item.combos||[]).length)+'点</span></div><strong class="arv-three-combos">'+combosHtml(item,r)+'</strong><p class="arv-three-ticket-reason">'+esc(item.reason||'')+'</p></div>';}).join('');
   var kochiFinal=r&&r.track==='高知'&&/ファイナル/.test(String(r.title||''));
   var isFusion=r.prediction&&r.prediction.modelVersion==='arvexq-empirical-fusion-v1';
   var methodology=isFusion?'発走前の実オッズと期待回収率で選定・全券種合計最大5点':
     kochiFinal?'高知ファイナル：全出走馬から3着候補を評価・3連複と3連単の合計最大5点（未校正）':
     '旧方式の保存済み発走前買い目・全券種合計最大5点';
   // Keep the win-EV list visible alongside the full grouped bets: it
   // is part of the same verified product (unifiedForecast ticketPlan)
   // and was previously only rendered by the reference-plan branch
   // below. Same markup and wording as that branch. Display filter
   // (user decision 2026-11-04): only the frozen candidate rule —
   // expected value >= 1.25 AND win probability >= 5%. The payload
   // still carries every runner's EV; this is display only.
   var model=r.unifiedForecast||{};
   var rosterNames={};
   (model.roster||[]).forEach(function(h){rosterNames[h.horseNumber]=h.name||'';});
   var winEvRaw=(model.ticketPlan||{}).winExpectedValues||[];
   var placeEvRaw=Array.isArray((model.ticketPlan||{}).placeExpectedValues)?model.ticketPlan.placeExpectedValues:null;
   var evSection='';
   if(placeEvRaw){
     var winByNo={};
     winEvRaw.forEach(function(x){if(x&&x.horseNumber!=null)winByNo[x.horseNumber]=x;});
     evSection=combinedEvSection(placeEvRaw,model.ticketPlan.combinedPicks||[],winByNo,rosterNames,marksByNoOf(r),evLabel,evNote);
   }else{
   var winEv=winEvRaw.filter(function(x){return x&&
     Number.isFinite(Number(x.expectedValue))&&Number(x.expectedValue)>=1.25&&
     Number.isFinite(Number(x.odds))&&Number(x.odds)>=1&&
     Number.isFinite(Number(x.winProbability))&&Number(x.winProbability)>=0.05&&
     (model.roster||[]).some(function(h){return h.horseNumber===x.horseNumber;});});
   var evRows=winEv.slice(0,5).map(function(x){
     return '<div class="arv-three-ticket"><div class="arv-three-ticket-head"><b>単勝 '+
        esc(x.horseNumber)+'番'+(rosterNames[x.horseNumber]?' '+esc(rosterNames[x.horseNumber]):'')+'</b>'+
        '<span class="arv-three-count">期待値 '+esc(Number(x.expectedValue).toFixed(2))+'</span></div>'+
        '<p class="arv-three-ticket-reason">勝率推定 '+esc((Number(x.winProbability)*100).toFixed(1))+
        '% × 単勝オッズ '+esc(Number(x.odds).toFixed(1))+'（'+evLabel+'）</p></div>';
   }).join('');
   evSection=winEvRaw.length?'<section class="arv-three-section"><h3>単勝期待値（'+evLabel+'）</h3>'+
     '<p class="arv-three-ticket-reason">表示条件：期待値1.25以上・勝率5%以上</p>'+
     (evRows||'<p class="arv-three-ticket-reason">対象馬なし</p>')+
     '<p class="arv-three-ticket-reason">'+evNote+'</p></section>':'';
   }
   return '<div class="ai-bet-box arv-three-bet"><div class="ai-bet-title">おすすめ買い目</div><p class="arv-three-fixed">'+esc(methodology)+'</p>'+rows+evSection+'</div>';
 }
 // Never mix an unrelated historical morning receipt into a ready Stage64
 // product when the server did not provide matching ticket evidence.
 if(r&&r.predictionStatus==='ready'&&r.prediction&&
    r.prediction.modelVersion==='arvexq-stage64-product-v1')
   return '<div class="ai-bet-box"><p class="muted">保存済み旧方式の買い目データが未取得です。</p></div>';
 var service=root.ARVEXQProductionTickets;
 var plan=null;
 if(r&&service&&service.build)plan=service.build(r,p);
 else if(r&&service&&service.current){
   // Fallback only when build is unavailable: the shared current() slot
   // is overwritten by background prebuilds for OTHER races, so a plan
   // may be used only when its identity matches the page race exactly.
   // With no race argument the slot is never consulted (unacquired).
   var shared=service.current();
   if(shared&&shared.raceId===r.id&&shared.raceDate===r.date)plan=shared;
 }
 // The unified reference plan carries its pre-off capture time as
 // referenceCapturedAt instead of fixedAt; both mean the combinations
 // were fixed before the off (the unified gate enforces capturedAt<post).
 var fixedAt=plan&&(plan.fixedAt||plan.referenceCapturedAt);
 if(!plan||!fixedAt||!Array.isArray(plan.items)||!plan.items.length){
   return '<div class="ai-bet-box"><p class="muted">発走前に検証・保存されたおすすめ買い目が未取得です。後付けで作りません。</p>'+revisionStatus(r)+'</div>';
 }
 var list=plan.items.map(function(item){
   var combos=combosHtml(item,r);
   return '<div class="arv-three-ticket"><div class="arv-three-ticket-head"><b>'+
      esc(item.kind)+'</b><span class="arv-three-count">'+esc((item.combos||[]).length)+'点</span></div>'+
      '<strong class="arv-three-combos">'+combos+'</strong>'+
      (item.reason?'<p class="arv-three-ticket-reason">'+esc(item.reason)+'</p>':'')+'</div>';
 }).join('');
 var evSection='';
 if(Array.isArray(plan.placeExpectedValues)){
   // Combined gate display, same rule as the server-bets branch.
   var winByNoP={},namesP={};
   (plan.winExpectedValues||[]).forEach(function(x){if(x&&x.horseNumber!=null){winByNoP[x.horseNumber]=x;if(x.name)namesP[x.horseNumber]=x.name;}});
   plan.placeExpectedValues.forEach(function(x){if(x&&x.horseNumber!=null&&x.name)namesP[x.horseNumber]=x.name;});
   evSection=combinedEvSection(plan.placeExpectedValues,plan.combinedPicks||[],winByNoP,namesP,marksByNoOf(r),evLabel,evNote);
 }else{
 // Same display rule as the server-bets branch above (user decision
 // 2026-11-04): only expected value >= 1.25 AND win probability >= 5%.
 var evPicks=(plan.winExpectedValues||[]).filter(function(x){return x&&
   Number.isFinite(Number(x.expectedValue))&&Number(x.expectedValue)>=1.25&&
   Number.isFinite(Number(x.winProbability))&&Number(x.winProbability)>=0.05;});
 var evRows=evPicks.slice(0,5).map(function(x){
   return '<div class="arv-three-ticket"><div class="arv-three-ticket-head"><b>単勝 '+
      esc(x.horseNumber)+'番'+(x.name?' '+esc(x.name):'')+'</b>'+
      '<span class="arv-three-count">期待値 '+esc(Number(x.expectedValue).toFixed(2))+'</span></div>'+
      '<p class="arv-three-ticket-reason">勝率推定 '+esc((Number(x.winProbability)*100).toFixed(1))+
      '% × 単勝オッズ '+esc(Number(x.odds).toFixed(1))+'（'+evLabel+'）</p></div>';
 }).join('');
 evSection=(plan.winExpectedValues||[]).length?'<section class="arv-three-section"><h3>単勝期待値（'+evLabel+'）</h3>'+
   '<p class="arv-three-ticket-reason">表示条件：期待値1.25以上・勝率5%以上</p>'+
   (evRows||'<p class="arv-three-ticket-reason">対象馬なし</p>')+
   '<p class="arv-three-ticket-reason">'+evNote+'</p></section>':'';
 }
 return '<div class="ai-bet-box arv-three-bet">'+
   '<div class="ai-bet-title">おすすめ買い目</div>'+
   '<p class="arv-three-fixed">発走前固定 '+esc(fixedAt)+'</p>'+
   '<section class="arv-three-section"><h3>おすすめ買い目</h3>'+list+'</section>'+
   evSection+
   '<p class="arv-three-provisional">保存された組み合わせをそのまま表示。発走後の再計算はしていません。</p>'+
   '</div>';
}
