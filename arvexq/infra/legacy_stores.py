    '    def upsert(self, rows: list[dict]) -> int:\n'
    '        n = 0\n'
    '        with self.conn:\n'
    '            for raw in rows:\n'
    '                incoming = normalize_central_race(raw)\n'
    '                if not incoming:\n'
    '                    continue\n'
    '                old_row=self.conn.execute("SELECT payload FROM central_races WHERE id=?",(incoming["id"],)).fetchone()\n'
    '                if old_row:\n'
    '                    try:old=json.loads(old_row["payload"])\n'
    '                    except Exception:old={}\n'
    '                    merged=dict(old) if isinstance(old,dict) else {}\n'
    '                    # Lightweight schedule rows must never erase a prepared card/result.\n'
    '                    for k,v in incoming.items():\n'
    '                        if k=="horses":\n'
    '                            if isinstance(v,list) and v:merged[k]=v\n'
    '                            continue\n'
    '                        if k=="result":\n'
    '                            if isinstance(v,dict) and v:merged[k]=v\n'
    '                            continue\n'
    '                        if k in {"weather","condition"}:\n'
    '                            if v not in (None,"","不明"):merged[k]=v\n'
    '                            elif k not in merged:merged[k]="不明"\n'
    '                            continue\n'
    '                        if k=="fieldSize":\n'
    '                            if int(v or 0)>0:merged[k]=int(v)\n'
    '                            continue\n'
    '                        if v not in (None,"",0,[]):\n'
    '                            merged[k]=v\n'
    '                        elif k not in merged:\n'
    '                            merged[k]=v\n'
