    '        dest = ARCHIVE_DIR / "daily_race.zip"\n'
    '        data = self._download(NAR_DAILY_RACE_URL, dest)\n'
    '        info = self.import_zip_bytes(data, cache_key, dest)\n'
    '        return {"status": "synced", **info}\n'
    '\n'
    '    def sync_month(self, year: int, month: int, force: bool = False) -> dict:\n'
    '        if not 1 <= month <= 12:\n'
    '            raise ValueError("month must be 1...12")\n'
    '        cache_key = f"month-{year:04d}-{month:02d}"\n'
    '        synced = self.store.synced_at(cache_key)\n'
    '        today = datetime.now().date()\n'
    '        is_current_month = (year == today.year and month == today.month)\n'
    '        current_ttl = int(os.getenv("NAR_CURRENT_MONTH_TTL_SECONDS", "300"))\n'
    '        if not force and synced:\n'
    '            age = int(time.time()) - synced\n'
    '            if (not is_current_month) or age < current_ttl:\n'
    '                return {"status": "cached", "cacheKey": cache_key}\n'
    '        dest = ARCHIVE_DIR / f"{year:04d}{month:02d}_race.zip"\n'
    '        url = NAR_MONTHLY_RACE_URL.format(year=year, month=month)\n'
    '        data = self._download(url, dest)\n'
    '        info = self.import_zip_bytes(data, cache_key, dest)\n'
    '        return {"status": "synced", **info}\n'
    '\n'
    '    def import_file(self, path: Path, cache_key: str | None = None) -> dict:\n'
    '        data = path.read_bytes()\n'
    '        key = cache_key or f"file-{path.name}-{int(path.stat().st_mtime)}"\n'
    '        return self.import_zip_bytes(data, key, path)\n'
    '\n'
