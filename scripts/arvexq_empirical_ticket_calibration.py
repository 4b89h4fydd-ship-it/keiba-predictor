#!/usr/bin/env python3
"""Read-only calibration from D1's already-saved original bets and official results.

Use only bets fixed before the published start, generated by the *new* model.
A race is counted once per main-ticket kind+number-of-points bucket, and only
if the official first three finishers are known. Never use today's results.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import date, timedelta, datetime
import json
import math
from pathlib import Path
import urllib.parse
import urllib.request

MODEL = "arvexq-true-run-pure-sectional-v2"
VERSION = "arvexq-empirical-ticket-hit-v1"
MIN_SAMPLES = 30
TARGET_HIT_RATE = 0.80
MIN_WILSON_LOWER = 0.65
KINDS = {"馬連": 2, "ワイド": 2, "馬単": 2, "3連複": 3, "3連単": 3}


def get_json(url: str):
    req = urllib.request.Request(url, headers={"accept":"application/json","user-agent":"ARVEXQ-HitCalibration/1"})
    with urllib.request.urlopen(req, timeout=12) as response:
        return json.loads(response.read().decode("utf-8"))


def selected_main_ticket(bet):
    if not isinstance(bet, dict):
        return None
    if bet.get("engineVersion") != MODEL or bet.get("captureStatus") == "failed":
        return None
    if str(bet.get("decision") or "") not in {"購入候補", "通常買い", "強く買う"}:
        return None
    for item in bet.get("items") or []:
        if not isinstance(item, dict) or item.get("level") != "本線":
            continue
        kind = item.get("kind")
        combos = item.get("combos")
        if kind not in KINDS or not isinstance(combos, list) or not 1 <= len(combos) <= 12:
            return None
        if not all(isinstance(c, list) and len(c) == KINDS[kind]
                   and len(set(map(str, c))) == len(c) for c in combos):
            return None
        return kind, combos
    return None


def ticket_hit(kind, combo, top3):
    a, b, c = top3
    values = tuple(int(x) for x in combo)
    if kind == "馬連":
        return set(values) == {a, b}
    if kind == "ワイド":
        return set(values).issubset({a, b, c})
    if kind == "馬単":
        return values == (a, b)
    if kind == "3連複":
        return set(values) == {a, b, c}
    if kind == "3連単":
        return values == (a, b, c)
    return False


def sealed_result(detail, cutoff_date):
    if not isinstance(detail, dict) or str(detail.get("date") or "") >= cutoff_date:
        return None
    bet = detail.get("preRaceBet") or {}
    item = selected_main_ticket(bet)
    if item is None:
        return None
    try:
        post = datetime.fromisoformat(str(detail["date"]) + "T" +
                                     str(detail.get("scheduledStartTime") or detail.get("startTime") or "")[:5] +
                                     ":00+09:00")
        sealed = datetime.fromisoformat(str(bet.get("fixedAt") or "").replace("Z", "+00:00"))
        if sealed >= post:
            return None
    except (ValueError, TypeError, KeyError):
        return None
    result = detail.get("result") or {}
    if result.get("status") not in ("確定", "official", "final") and detail.get("raceStatus") != "確定":
        return None
    finishers = {}
    for h in result.get("finishers") or []:
        if not isinstance(h, dict):
            continue
        try:
            rank, no = int(h.get("finish")), int(h.get("horseNumber"))
            if rank in (1, 2, 3) and no > 0 and rank not in finishers:
                finishers[rank] = no
        except (TypeError, ValueError):
            continue
    if len(finishers) != 3 or len(set(finishers.values())) != 3:
        return None
    kind, combos = item
    target = tuple(finishers[i] for i in (1, 2, 3))
    return {"id": str(detail.get("id")), "date": str(detail.get("date")),
            "model": MODEL, "kind": kind, "points": len(combos),
            "hit": any(ticket_hit(kind, combo, target) for combo in combos)}


def wilson_lower(wins, count, z=1.96):
    if count <= 0:
        return 0.
    p = wins / count
    d = 1. + z*z/count
    return max(0., (p + z*z/(2*count) -
                     z*math.sqrt((p*(1-p) + z*z/(4*count))/count)) / d)


def summarize(records, target_date):
    valid = [v for v in records.values() if v.get("model") == MODEL
             and str(v.get("date") or "") < target_date]
    buckets = {}
    for item in valid:
        key = str(item["kind"]) + "|" + str(item["points"])
        box = buckets.setdefault(key, {"kind": item["kind"], "points": item["points"],
                                       "sample": 0, "wins": 0})
        box["sample"] += 1
        box["wins"] += int(bool(item["hit"]))
    for box in buckets.values():
        count, wins = box["sample"], box["wins"]
        box["hitRate"] = round(wins / count, 6)
        box["wilsonLower95"] = round(wilson_lower(wins, count), 6)
        box["qualified"] = (count >= MIN_SAMPLES and
                            box["hitRate"] >= TARGET_HIT_RATE and
                            box["wilsonLower95"] >= MIN_WILSON_LOWER)
    return {"version": VERSION, "modelVersion": MODEL, "asOfDate": target_date,
            "definition": "one main-ticket item wins if any pre-off combination hit",
            "minimumSample": MIN_SAMPLES, "minimumObservedHitRate": TARGET_HIT_RATE,
            "minimumWilsonLower95": MIN_WILSON_LOWER,
            "totalVerifiedRaces": len(valid), "buckets": buckets,
            "status": "verified" if any(b["qualified"] for b in buckets.values()) else "insufficient-evidence"}


def fetch_previous_day(api_base, target_date):
    prev = (date.fromisoformat(target_date)-timedelta(days=1)).isoformat()
    base = api_base.rstrip("/")
    try:
        day = get_json(base + "/api/day?date=" + prev + "&details=0")
    except Exception as exc:
        raise RuntimeError(f"HIT_RATE_DAY_UNAVAILABLE {prev}: {exc}") from exc
    if not isinstance(day, dict) or not isinstance(day.get("races"), list):
        raise RuntimeError(f"HIT_RATE_DAY_INVALID {prev}: missing races array")
    ids = [str(r["id"]) for r in day.get("races") or []
           if isinstance(r, dict) and r.get("id")]
    def one(rid):
        try:
            obj = get_json(base + "/api/race/" + urllib.parse.quote(rid, safe=""))
            return obj.get("detail") if isinstance(obj.get("detail"), dict) else obj
        except Exception as exc:
            raise RuntimeError(f"HIT_RATE_RACE_UNAVAILABLE {rid}: {exc}") from exc
    with ThreadPoolExecutor(max_workers=6) as pool:
        details = list(pool.map(one, ids))
    if any(not isinstance(x, dict) for x in details):
        raise RuntimeError(f"HIT_RATE_RACE_INVALID {prev}: malformed response")
    return details


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    ap.add_argument("--api-base", default="")
    ap.add_argument("--input", default="", help="Test fixture JSON with details array")
    ap.add_argument("--records", default="arvexq/ui/static/morning/hit_rate_records.json")
    ap.add_argument("--output", default="arvexq/ui/static/morning/hit_rate_calibration.json")
    args = ap.parse_args()
    prior = Path(args.records)
    records = json.loads(prior.read_text(encoding="utf-8")) if prior.exists() else {}
    if not isinstance(records, dict):
        raise ValueError("invalid calibration historical records")
    if args.input:
        data = json.loads(Path(args.input).read_text(encoding="utf-8"))
        details = data.get("details") or []
    elif args.api_base:
        details = fetch_previous_day(args.api_base, args.date)
    else:
        details = []
    for detail in details:
        item = sealed_result(detail, args.date)
        if item is not None and item["id"]:
            records[item["id"]] = item
    cal = summarize(records, args.date)
    Path(args.records).parent.mkdir(parents=True, exist_ok=True)
    Path(args.records).write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    Path(args.output).write_text(json.dumps(cal, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("EMPIRICAL_TICKET_HIT_AUDIT", json.dumps({"verified":cal["totalVerifiedRaces"],
          "qualifiedBuckets":[k for k,v in cal["buckets"].items() if v["qualified"]],
          "asOf":args.date}, ensure_ascii=False))


if __name__ == "__main__":
    main()
