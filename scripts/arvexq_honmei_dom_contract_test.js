'use strict';
const assert=require('node:assert/strict'),verify=require('./arvexq_honmei_dom_contract');
const win={horseNumber:1,mark:'◎',win:true,axis:false},axis={horseNumber:2,mark:'◎',win:false,axis:true};
assert.throws(()=>verify([win,axis],'split live honmei'),/multiple unified/);
assert.doesNotThrow(()=>verify([{mark:'◎',win:true,axis:true}],'one unified horse'));
assert.throws(()=>verify([win,{mark:'○',win:false,axis:true}],'split live roles'),/same horse/);
assert.doesNotThrow(()=>verify([{mark:'◎',win:false,axis:false}],'one original without roles'));
assert.doesNotThrow(()=>verify([win,axis],'known legacy deployment',{legacyPolicy:true}));
assert.doesNotThrow(()=>verify([win,axis],'preserved historical original',{originalHonmeiHorseNumbers:[1,2]}));
assert.throws(()=>verify([win,axis],'wrong original',{originalHonmeiHorseNumbers:[1,3]}),/immutable original/);
assert.throws(()=>verify([win,win],'duplicate winner'),/duplicate win role/);
assert.throws(()=>verify([axis,axis],'duplicate axis'),/duplicate podium-axis role/);
assert.throws(()=>verify([{mark:'◎'},{mark:'◎'}],'two untyped live'),/multiple unified/);
console.log('HONMEI_UNIFIED_AND_IMMUTABLE_ORIGINAL_CONTRACT_PASS');
